// Variable declaration
let price = 50;
let quantity = 3;

// Constant declaration
const taxRate = 0.06;

// Operator usage
let subtotal = price * quantity;      // Multiplication operator (*)
let tax = subtotal * taxRate;         // Multiplication operator (*)
let total = subtotal + tax;            // Addition operator (+)

// Output result
console.log("Subtotal: RM" + subtotal);
console.log("Tax: RM" + tax);
console.log("Total Price: RM" + total);
